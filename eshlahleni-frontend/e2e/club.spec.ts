test('administrator pagination, forbidden/missing records and expired sessions', async ({ page }) => {
  let failure = 0; const pages: string[] = [];
  const applicant = { applicationId: '11111111-1111-4111-8111-111111111111', firstName: 'Test', lastName: 'Applicant', email: 'test@example.test', phoneNumber: '+27841234567', dateOfBirth: '1990-01-01', termsAccepted: true, privacyConsent: true, status: 'Pending', submittedAtUtc: '2026-11-06T10:00:00Z' };
  await page.route('**/api/v1/**', route => {
    const url = new URL(route.request().url());
    if (url.pathname.endsWith('/auth/login')) return route.fulfill({ json: { accessToken: 'temporary-browser-test-token', tokenType: 'Bearer', expiresIn: 1800 } });
    if (failure) return route.fulfill({ status: failure, json: { status: failure } });
    pages.push(url.searchParams.get('page') ?? '1');
    return route.fulfill({ json: { items: url.pathname.endsWith('/members') ? [] : [applicant], totalCount: url.pathname.endsWith('/members') ? 0 : 45, page: Number(url.searchParams.get('page') ?? '1'), pageSize: 20 } });
  });
  await page.goto('/admin/login'); await page.locator('input#adminEmail').fill('admin@example.test'); await page.locator('input#adminPassword').fill('test-password'); await page.getByRole('button', { name: 'Sign in', exact: false }).click();
  await expect(page).toHaveURL(/\/admin$/); await page.locator('.admin-nav').getByRole('link', { name: 'Membership Applications' }).click();
  await page.getByRole('button', { name: 'Next page' }).click(); await expect(page).toHaveURL(/page=2/); await expect.poll(() => pages).toContain('2');
  failure = 403; await page.locator('#applicationStatus').selectOption('Approved'); await page.getByRole('button', { name: 'Search', exact: false }).click();
  await expect(page.getByText('Your account does not have permission', { exact: false })).toBeVisible();
  failure = 404; await page.getByRole('button', { name: 'Try again', exact: false }).click(); await expect(page.getByText('This record could not be found.', { exact: false })).toBeVisible();
  failure = 401; await page.getByRole('button', { name: 'Try again', exact: false }).click(); await expect(page).toHaveURL(/\/admin\/login/); await expect(page.getByText('Your session has ended.', { exact: false })).toBeVisible();
});

